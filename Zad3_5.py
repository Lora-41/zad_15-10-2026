day = int(input("Въведете номер на ден от седмицата (от 1 до 7): "))

if day == 1:
    print("Понеделник")
elif day == 2:
    print("Вторник")
elif day == 3:
    print("Сряда")
elif day == 4:
    print("Четвъртък")
elif day == 5:
    print("Петък")
elif day == 6:
    print("Събота")
elif day == 7:
    print("Неделя")
else:
    print("Грешка: Въведете число между 1 и 7.")
    